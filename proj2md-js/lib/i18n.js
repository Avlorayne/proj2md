let _CURRENT_LANG = 'zh';
function detectSystemLang() {
  const codes = [];
  for (const v of ['LC_ALL', 'LC_MESSAGES', 'LC_CTYPE', 'LANG', 'LANGUAGE']) {
    const e = process.env[v];
    if (e) codes.push(e);
  }
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale;
    if (loc) codes.push(loc);
  } catch (e) { /* ignore */ }
  for (const c of codes) {
    if (c && String(c).toLowerCase().startsWith('zh')) return 'zh';
  }
  return 'en';
}
function setLang(lang) {
  let s = String(lang === undefined || lang === null ? 'auto' : lang).trim().toLowerCase();
  if (s === '' || s === 'auto' || s === 'system' || s === 'default') {
    _CURRENT_LANG = detectSystemLang();
  } else {
    s = s.replace(/-/g, '_').split('_')[0].split('.')[0];
    _CURRENT_LANG = Object.prototype.hasOwnProperty.call(LANG_TEXTS, s) ? s : 'en';
  }
  return _CURRENT_LANG;
}
function t(key, kw) {
  let text = LANG_TEXTS[_CURRENT_LANG] ? LANG_TEXTS[_CURRENT_LANG][key] : undefined;
  if (text === undefined || text === null) text = (LANG_TEXTS.en && LANG_TEXTS.en[key]) || key;
  if (kw && typeof kw === 'object') {
    // 支持 Python 风格的 {name:g} 格式说明（忽略 ：g，直接替换值）
    text = text.replace(/\{(\w+)(?::\w+)?\}/g, (m, k) =>
      Object.prototype.hasOwnProperty.call(kw, k) ? String(kw[k]) : m);
  }
  return text;
}
